// Builds the public website (duckbook.khoadev.id.vn): homepage, privacy policy and terms for the
// Google sign-in screen. Static pages only; it has no link to any notebook.
//
//   node site/build.ts
//
// Output in site/dist: public/ (plain static files) and worker.js (one self-contained Cloudflare
// Worker module with every file embedded). <!--CONTACT--> in the pages becomes CONTACT below.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const src = path.join(here, 'public')
const out = path.join(here, 'dist')

const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
}

/** Public support and privacy contact, approved by the owner (2026-11-03). */
const CONTACT = 'ndkhoa1000@gmail.com'
const contactHtml = `<a href="mailto:${CONTACT}">${CONTACT}</a>`

fs.rmSync(out, { recursive: true, force: true })
const files: Record<string, { type: string; text?: string; base64?: string }> = {}
const walk = (dir: string) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      walk(full)
      continue
    }
    const rel = '/' + path.relative(src, full).split(path.sep).join('/')
    const ext = path.extname(rel)
    const type = TYPES[ext]
    if (!type) throw new Error(`No content type for ${rel}`)
    let data = fs.readFileSync(full)
    if (ext === '.html') data = Buffer.from(data.toString('utf8').replaceAll('<!--CONTACT-->', contactHtml))
    const dest = path.join(out, 'public', rel)
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, data)
    files[rel] = type.startsWith('text/') ? { type, text: data.toString('utf8') } : { type, base64: data.toString('base64') }
  }
}
walk(src)

const worker = `// Generated by site/build.ts. Do not edit; edit site/public and rebuild.
const FILES = ${JSON.stringify(files)}
const ROUTES = { '/': '/index.html', '/privacy': '/privacy.html', '/terms': '/terms.html' }
const PAGES = { '/index.html': '/', '/privacy.html': '/privacy', '/terms.html': '/terms' }
const SECURITY = {
  'Content-Security-Policy': "default-src 'none'; style-src 'self'; img-src 'self'; font-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Strict-Transport-Security': 'max-age=31536000',
}
const bodies = new Map()
const body = (f) => {
  if (f.text !== undefined) return f.text
  if (!bodies.has(f)) bodies.set(f, Uint8Array.from(atob(f.base64), (c) => c.charCodeAt(0)))
  return bodies.get(f)
}

export default {
  async fetch(request) {
    const url = new URL(request.url)
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD', ...SECURITY } })
    if (PAGES[url.pathname]) return Response.redirect(new URL(PAGES[url.pathname], url).toString(), 301)
    if (url.pathname.length > 1 && url.pathname.endsWith('/')) return Response.redirect(new URL(url.pathname.replace(/\\/+$/, ''), url).toString(), 301)
    const key = ROUTES[url.pathname] ?? url.pathname
    const file = FILES[key]
    const found = !!file && !key.endsWith('/404.html')
    const f = found ? file : FILES['/404.html']
    const cache = f.type.startsWith('text/html') ? 'public, max-age=300' : 'public, max-age=86400'
    return new Response(request.method === 'HEAD' ? null : body(f), { status: found ? 200 : 404, headers: { 'Content-Type': f.type, 'Cache-Control': cache, ...SECURITY } })
  },
}
`
fs.writeFileSync(path.join(out, 'worker.js'), worker)
console.log(`site/dist: ${Object.keys(files).length} files, worker.js ${(worker.length / 1024).toFixed(0)} KB`)
